// Generates 0004_reference_data.sql from the shared tokens so the database, website and app use the same amenity list.
// Run:  node --experimental-strip-types supabase/scripts/gen-reference.mjs
import { writeFileSync } from "node:fs";
import { AMENITIES } from "../../packages/tokens/src/amenities.ts";

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const rows = AMENITIES.map((a, i) =>
  `  (${q(a.key)}, ${q(a.group)}, ${q(a.label)}, ${q(a.icon)}, ${q(a.scope)}, ${q(a.spec)}, ${q(a.specLabel ?? null)}, ${a.filterable}, ${q(a.filterLabel ?? null)}, ${i + 1})`
).join(",\n");

const areas = [
  ["maitama", "Maitama", 9.087, 7.4939], ["asokoro", "Asokoro", 9.0396, 7.5186], ["wuse-2", "Wuse 2", 9.0765, 7.4698],
  ["garki", "Garki", 9.0333, 7.4833], ["jabi", "Jabi", 9.07, 7.418], ["utako", "Utako", 9.068, 7.44],
  ["gwarinpa", "Gwarinpa", 9.114, 7.4], ["katampe", "Katampe", 9.11, 7.465], ["life-camp", "Life Camp", 9.095, 7.387],
  ["lugbe", "Lugbe", 8.983, 7.379], ["kubwa", "Kubwa", 9.15, 7.33], ["apo", "Apo", 8.993, 7.503],
  ["lokogoma", "Lokogoma", 8.988, 7.44], ["guzape", "Guzape", 9.01, 7.5], ["wuye", "Wuye", 9.063, 7.465],
  ["cbd", "Central Business District", 9.058, 7.49], ["jahi", "Jahi", 9.09, 7.43], ["kado", "Kado", 9.1, 7.445],
];
const arows = areas.map(([s, n, la, ln]) => `  (${q(s)}, ${q(n)}, ${la}, ${ln})`).join(",\n");

const sql = `-- Spotted · 0004 reference data (GENERATED by supabase/scripts/gen-reference.mjs, do not edit by hand)

insert into amenity_catalog (key, group_key, label, icon, scope, spec_kind, spec_label, filterable, filter_label, sort) values
${rows}
on conflict (key) do update set group_key = excluded.group_key, label = excluded.label, icon = excluded.icon, scope = excluded.scope,
  spec_kind = excluded.spec_kind, spec_label = excluded.spec_label, filterable = excluded.filterable, filter_label = excluded.filter_label, sort = excluded.sort;

-- Approximate centre points of Abuja districts (used for map framing and "near me" sorting).
insert into areas (slug, name, lat, lng) values
${arows}
on conflict (slug) do nothing;

-- Editable placeholders. Change any of these in the Table Editor (or the admin screen later), no code change needed.
insert into app_settings (key, value, note) values
  ('host_commission_pct',     '10',  'PLACEHOLDER. Percent Spotted keeps from each stay. Not decided yet. Owners pay nothing during their free months.'),
  ('guest_service_fee_pct',   '0',   'Percent added on top for guests. 0 = guests pay the room price plus cleaning fee only.'),
  ('free_months_for_new_owners', '2', 'Months a new owner pays no commission.'),
  ('booking_hold_minutes',    '20',  'How long dates stay held while a guest pays.'),
  ('min_photos_per_room',     '5',   'Documentation only. The 5-photo rule is enforced by the database trigger.')
on conflict (key) do nothing;
`;
writeFileSync(new URL("../migrations/0004_reference_data.sql", import.meta.url), sql);
console.log("wrote 0004 with", AMENITIES.length, "amenities and", areas.length, "areas");
